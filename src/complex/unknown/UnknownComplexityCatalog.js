const CATALOG =
    new Map(
        DEFINITIONS.map(
            definition => [
                definition.code,
                definition
            ]
        )
    );

export function getUnknownComplexityDefinition(
    code
) {
    return CATALOG.get(code) ?? null;
}

export function listUnknownComplexityDefinitions() {
    return [...DEFINITIONS];
}

export function isUnknownComplexityCode(code) {
    return CATALOG.has(code);
}

function entry(code, phase, category) {
    return Object.freeze({
        code,
        phase,
        category,
        recoverability:
            category === C.SAFETY_LIMIT
                ? "increase-safe-capacity"
                : category ===
                    C.NUMERIC_SOLVER_LIMIT
                    ? "extend-solver"
                    : "extend-analyzer"
    });
}
